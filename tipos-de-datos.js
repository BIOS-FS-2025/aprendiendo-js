// Tipos de datos

// String o cadena de caracteres
let nombre = "Miguel";
console.log('El dato es de tipo', typeof nombre)
// Number o numero
let edad = 27;
console.log('El dato es de tipo', typeof edad)
// Booleano o boolean
let esMayorDeEdad = true;
console.log('El dato es de tipo', typeof esMayorDeEdad)
// Float o flotante // En javascript no existe el tipo float, solo number
let flotante = 30.5;
console.log('El dato es de tipo flotante', typeof flotante)
// null
let tipoNull = null;
console.log('El dato es de tipo', typeof tipoNull)
// undefined
let tipoUndefined;
console.log('El dato es de tipo', typeof tipoUndefined)
// Object o objeto
let perro = {
  nombre: "Firulais",
  raza: "Labrador",
  edad: 2,
  color: "Negro"
}
console.log('El dato es de tipo', typeof perro)
// Array o arreglo
let coloresPrimarios = ["Rojo", "Azul", "Amarillo"];
console.log('El dato es de tipo', typeof coloresPrimarios)